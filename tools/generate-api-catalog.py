#!/usr/bin/env python3
"""Generate the Lua4RS function browser catalogue from RetroShare wrappers.

Usage: python tools/generate-api-catalog.py ../../jsonapi-generator/src/jsonapi-wrappers.inl
Add --check to compare with the existing header without modifying it.
Only Python's standard library is required. This parses generated wrappers,
not arbitrary C++; manual API wrappers are intentionally excluded.
"""

import argparse
import json
from pathlib import Path
import re
import sys


def generate(source):
    handlers = list(re.finditer(r'registerHandler\s*\(\s*"([^"\n]+)"', source))
    if not handlers:
        raise ValueError("No generated registerHandler entries found")
    entries = {}
    for index, match in enumerate(handlers):
        path = match.group(1)
        end = handlers[index + 1].start() if index + 1 < len(handlers) else len(source)
        body = source[match.end():end]
        if path in entries:
            raise ValueError("Duplicate endpoint: " + path)
        if "text/event-stream" in body:
            entries[path] = ("", "Streaming endpoint: unavailable through jsonapi.call. "
                             "Use GUI Automation triggers; jsonapi.subscribe in the "
                             "standalone runner supports rsEvents only.")
            continue
        markers = ("// deserialize input parameters from JSON",
                   "// call retroshare C++ API",
                   "// serialize out parameters and return value to JSON",
                   "// return them to the API caller")
        positions = [body.find(marker) for marker in markers]
        if min(positions) < 0 or positions != sorted(positions):
            raise ValueError("Unrecognized wrapper format: " + path)
        fields = lambda text: re.findall(r'RS_SERIAL_PROCESS\s*\(\s*(\w+)\s*\)', text)
        inputs = fields(body[positions[0]:positions[1]])
        outputs = fields(body[positions[2]:positions[3]])
        declarations = body[:positions[0]]
        types = []
        for name in inputs:
            declaration = re.search(r'^\s*([^;{}\n]+?)\s+' + re.escape(name)
                                    + r'\s*(?:=[^;]*)?;\s*$', declarations, re.MULTILINE)
            if not declaration:
                raise ValueError("Missing input declaration for " + path + ": " + name)
            types.append(name + ": " + " ".join(declaration.group(1).split()))
        type_text = "; ".join(types) or "none"
        snippet = "-- JSON API: configure the connection first.\n"
        if inputs:
            snippet += "-- Define input variables above this call. Types: " + type_text + "\n"
            for name in inputs:
                snippet += f'assert({name} ~= nil, "Set {name} before calling this endpoint")\n'
            parameters = "{\n" + ",\n".join(f"    {name} = {name}" for name in inputs) + "\n}"
        else:
            parameters = "{}"
        snippet += f'local result, err, status = jsonapi.call("{path}", {parameters})\n'
        snippet += "assert(result, err)\nprint(jsonapi.encode(result))\n"
        hint = ("Source-build catalogue; availability depends on the running server.\n"
                + "Inputs: " + type_text + "\nResponse fields: " + (", ".join(outputs) or "none")
                + "\nInspect result.retval when present: transport success is not method success.")
        entries[path] = snippet, hint
    lines = ["// Generated by tools/generate-api-catalog.py; do not edit.",
             "#pragma once",
             "struct JsonApiEntry { const char* path; const char* snippet; const char* hint; };",
             "static const JsonApiEntry jsonApiCatalog[] = {"]
    for path, (snippet, hint) in sorted(entries.items()):
        lines.append("    {" + ", ".join(json.dumps(value, ensure_ascii=True)
                                        for value in (path, snippet, hint)) + "},")
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("wrappers", type=Path)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "gui" / "JsonApiCatalog.h")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        result = generate(args.wrappers.read_text(encoding="utf-8-sig"))
        if args.check:
            if args.output.read_text(encoding="utf-8") != result:
                print("Catalogue differs: " + str(args.output), file=sys.stderr)
                return 1
            print("Catalogue matches: " + str(args.output))
        else:
            args.output.write_text(result, encoding="utf-8", newline="\n")
            print("Generated " + str(args.output))
    except (OSError, ValueError) as error:
        parser.exit(1, str(error) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
